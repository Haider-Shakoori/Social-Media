"use client";
import {useCallback,useEffect,useState} from "react";
const API=process.env.NEXT_PUBLIC_API_BASE_URL||"http://localhost:4000/api/v1";
type Readiness={providers:{network:"meta"|"instagram"|"x";configured:boolean;testingEnabled:boolean;paidApiConsent:boolean|null;canPublish:boolean}[];
 accounts:{id:string;platform:string;externalAccountId:string|null;externalAccountName:string|null;state:string;tokenExpiresAt:string|null;lastHealthCheckedAt?:string|null;lastHealthReason?:string|null}[]};
type Choice={id:string;name:string;platform:"facebook"|"instagram"|"x"};
async function apiCall<T>(path:string,method="GET",body?:unknown):Promise<T>{
 const r=await fetch(API+path,{method,credentials:"include",cache:"no-store",
  headers:body===undefined?undefined:{"Content-Type":"application/json"},
  body:body===undefined?undefined:JSON.stringify(body)});
 const data=await r.json().catch(()=>({}));
 if(!r.ok)throw new Error(typeof data.message==="string"?data.message:"Operation failed");
 return data as T;
}
export function MetaXConnections({tenantId,workspaceId,brandId}:{tenantId:string;workspaceId:string;brandId:string}){
 const [status,setStatus]=useState<Readiness|null>(null);
 const [attempt,setAttempt]=useState(""),[choices,setChoices]=useState<Choice[]>([]),[error,setError]=useState(""),[note,setNote]=useState("");
 const [busy,setBusy]=useState(false);
 const root="/tenants/"+tenantId+"/workspaces/"+workspaceId+"/brands/"+brandId+"/social";
 const refresh=useCallback(async()=>{setStatus(await apiCall<Readiness>(root+"/readiness"));},[root]);
 useEffect(()=>{let live=true;setStatus(null);setNote("");setError("");
  void refresh().catch(e=>{if(live)setError(e instanceof Error?e.message:"Account status unavailable");});
  return()=>{live=false;};
 },[refresh]);
 useEffect(()=>{
  const q=new URLSearchParams(window.location.search);
  const id=q.get("socialAttempt"),issue=q.get("socialConnectError");
  if(issue){
   const messages:Record<string,string>={
    authorization_cancelled:"Instagram authorization was cancelled. Retry and approve access in Instagram.",
    instagram_short_exchange:"Instagram returned an authorization code, but the first token exchange failed. Check the Instagram App Secret (not the access token) and the exact OAuth redirect URI in Meta Developer settings.",
    instagram_short_response:"Instagram returned an unexpected token response. Check the Instagram app configuration and retry.",
    instagram_long_exchange:"The Instagram temporary token was received, but the long-lived token exchange failed. Check the Instagram app credentials and API access.",
    instagram_long_response:"Instagram returned an invalid long-lived token response. Please retry the authorization.",
    instagram_profile_lookup:"Instagram issued an access token, but account details could not be loaded. Confirm the account and instagram_business_basic permission in Meta.",
    instagram_account_ineligible:"Instagram did not return an eligible Business or Creator account. Check the account type in Instagram settings.",
    instagram_identity_mismatch:"Instagram returned mismatched account identities. Restart authorization with one Instagram account."
   };
   setError(messages[issue]||"Instagram authorization could not be completed. Retry or check your Meta Developer app configuration.");
  }
  if(!id)return;
  let active=true;
  void apiCall<{accounts:Choice[];brandId:string}>("/social/oauth/attempts/"+id+"/accounts")
   .then(result=>{if(active&&result.brandId===brandId){setChoices(result.accounts);setAttempt(id);} else if(active){setError("Select the brand originally used for authorization.");}})
   .catch(()=>{if(active)setError("The social authorization has expired or belongs to another session.");});
  return()=>{active=false;};
 },[brandId]);
 async function start(network:"meta"|"instagram"|"x"){
  setBusy(true);setError("");setNote("");
  try{
   const {authorizationUrl}=await apiCall<{authorizationUrl:string}>(root+"/oauth/"+network+"/start","POST",{});
   // URL is generated by the backend from fixed, verified provider hosts.
   if(new URL(authorizationUrl).hostname!==(network==="meta"?"www.facebook.com":network==="instagram"?"www.instagram.com":"x.com"))throw new Error("Unexpected provider redirect");
   window.location.assign(authorizationUrl);
  }catch(e){setError(e instanceof Error?e.message:"Connection unavailable");setBusy(false);}
 }
 async function select(account:Choice){
  if(!attempt)return;
  setBusy(true);setError("");
  try{
   const result=await apiCall<{notice:string}>("/social/oauth/attempts/"+attempt+"/select","POST",{accountId:account.id,platform:account.platform});
   setNote(result.notice);setAttempt("");setChoices([]);await refresh();
   window.history.replaceState(null,"",window.location.pathname);
  }catch(e){setError(e instanceof Error?e.message:"Could not link account");}finally{setBusy(false);}
 }
 async function maintain(connectionId:string,operation:'health-check'|'refresh'){
  setBusy(true);setError("");setNote("");
  try{
   const result=await apiCall<{state:string;reason?:string;missingScopes?:string[]}>(root+"/accounts/"+connectionId+"/"+operation,"POST",{});
   setNote("Meta account: "+result.state.toLowerCase()+(result.missingScopes?.length?" — missing "+result.missingScopes.join(", "):""));
   await refresh();
  }catch(e){setError(e instanceof Error?e.message:"Account maintenance failed");}
  finally{setBusy(false);}
 }
 async function disconnect(connectionId:string){
  if(!window.confirm("Disconnect this account and erase locally stored credentials?"))return;
  setBusy(true);setError("");
  try{
   const result=await apiCall<{providerRevocation:string}>(root+"/accounts/"+connectionId+"/disconnect","POST",{});
   setNote(result.providerRevocation);await refresh();
  }catch(e){setError(e instanceof Error?e.message:"Disconnect failed");}finally{setBusy(false);}
 }
 return <section className="mt-7 rounded-2xl border border-white/10 bg-[#07131b] p-5">
  <p className="text-xs font-bold tracking-widest text-emerald-300">OFFICIAL ACCOUNT PILOT</p>
  <h3 className="mt-3 text-xl font-bold">Connect Facebook and Instagram</h3>
  <p className="mt-2 text-sm leading-7 text-slate-300">Connect Facebook Pages or Instagram Business/Creator accounts through their official, separate login flows. We never ask for your Meta password. Publishing remains disabled; X is manual-only for now.</p>
  {error&&<p role="alert" className="mt-4 text-sm text-rose-200">{error}</p>}
  {note&&<p role="status" className="mt-4 text-sm text-emerald-200">{note}</p>}
  <div className="mt-5 flex flex-wrap gap-3">
   {(status?.providers||[]).filter(p=>p.network==="meta"||p.network==="instagram").map(p=><div key={p.network} className="rounded-xl border border-white/15 p-4">
    <h4 className="font-bold">{p.network==="meta"?"Facebook Login — linked Pages":p.network==="instagram"?"Instagram Login — no Facebook Page required":"X (Twitter)"}</h4>
    <p className="mt-2 text-xs text-slate-400">{!p.configured?"Developer credentials missing":!p.testingEnabled?"Test access disabled by operator":p.network==="x"&&!p.paidApiConsent?"Cost approval required":"Configured for test authorization"}</p>
    <button type="button" disabled={busy||!p.configured||!p.testingEnabled||(p.network==="x"&&!p.paidApiConsent)}
     onClick={()=>void start(p.network)} className="mt-4 rounded-lg border border-emerald-300/30 px-4 py-2 text-sm font-semibold text-emerald-200 disabled:cursor-not-allowed disabled:opacity-40">
     Authorize {p.network==="meta"?"Facebook":p.network==="instagram"?"Instagram":"X"} account
    </button>
   </div>)}
  </div>
  {choices.length>0&&<div className="mt-6 border-t border-white/10 pt-5">
   <h4 className="font-bold">Select the authorized account</h4>
   <p className="mt-2 text-xs text-slate-400">Only accounts returned by your approved OAuth consent session appear here.</p>
   <div className="mt-3 space-y-2">{choices.map(a=><div key={a.platform+":"+a.id} className="flex flex-wrap items-center justify-between gap-3 rounded-xl border border-white/10 p-3">
    <span className="text-sm">{a.name} <span className="text-slate-400">({a.platform})</span></span>
    <button type="button" disabled={busy} onClick={()=>void select(a)} className="rounded-lg border border-emerald-300/30 px-4 py-2 text-sm font-bold text-emerald-200">Link to brand</button>
   </div>)}</div>
  </div>}
  {status?.accounts?.length? <div className="mt-6 border-t border-white/10 pt-5">
   <h4 className="font-semibold">Linked testing accounts</h4>
   <div className="mt-3 space-y-2">{status.accounts.map(a=><div key={a.id} className="flex flex-wrap justify-between gap-4 rounded-xl border border-white/10 p-3">
    <div><p className="text-sm font-semibold">{a.externalAccountName||a.platform}</p>
     <p className="mt-1 text-xs text-slate-400">{a.platform} · {a.state}{a.tokenExpiresAt?" · Expires "+new Date(a.tokenExpiresAt).toLocaleDateString():""}{a.lastHealthReason?" · Check: "+a.lastHealthReason.replaceAll("_"," "):""}</p></div>
    {a.state!=="DISCONNECTED"&&<div className="flex flex-wrap items-center gap-3">
      {(["facebook","instagram"].includes(a.platform))&&<><button type="button" disabled={busy} onClick={()=>void maintain(a.id,"health-check")} className="text-sm text-emerald-200">Check status</button><button type="button" disabled={busy} onClick={()=>void maintain(a.id,"refresh")} className="text-sm text-slate-200">Refresh token</button></>}
      <button type="button" disabled={busy} onClick={()=>void disconnect(a.id)} className="text-sm text-rose-200">Disconnect</button></div>}
   </div>)}</div>
  </div>:null}
 </section>;
}
